import sqlite3  # Importando a biblioteca SQL

# 1) Conectando com um db para consulta (connect e cursor)

conexao = sqlite3.connect('planta_industrial.db') # Conecta ao banco de dados (abre o arquivo)

cursor = conexao.cursor() # É a chave que abre a porta do arquivo do banco de dados na sua máquina ou na nuvem do Colab. Sem ela, o Python nem sabe qual arquivo você quer abrir ou criar. Sempre que for consultar o SQL é preciso essa linha!!

print("Conexão criada com sucesso:", conexao)
print("Cursor pronto para uso:", cursor)
print("Testando git!")
# mais uma linha (teste git)



# 2) Cria a nossa "planilha" ou scheme (tabela) chamada 'sensores'

cursor.execute("""
  CREATE TABLE IF NOT EXISTS sensores (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    equipamento TEXT,
    temperatura REAL,
    pressao REAL
  );
""")

# 3) Inserir dados de exemplo (como se fossem linhas preenchidas na planilha)

cursor.execute("INSERT INTO sensores (equipamento, temperatura, pressao) VALUES ('Reator_A', 85.5, 20.0);") # Aspas duplas em SQL significa comando ao cursor.
# Enquanto aspas simples é string.
cursor.execute("INSERT INTO sensores (equipamento, temperatura, pressao) VALUES ('Reator_B', 100.2, 40.5);")
cursor.execute("INSERT INTO sensores (equipamento, temperatura, pressao) VALUES ('Destilador_F', 89.6, 12.5);")

conexao.commit() # Salva as alterações no database.

# 4) A GRANDE MÁGICA DO SQL: O comando SELECT
# Aqui pedimos: "Selecione tudo (*) da tabela 'sensores' ONDE a temperatura seja maior que 80"

cursor.execute("SELECT * FROM sensores WHERE temperatura > 80.0;") #Aqui o banco de dados faz a busca, encontra as linhas que cumprem o requisito e as deixa guardadas "na memória temporária" do cursor. O banco fez o trabalho pesado de busca, mas os dados ainda estão lá dentro do servidor/arquivo do banco.

temperaturas_criticas = cursor.fetchall() # Fetchall = buscar tudo. Esse comando pega tudo e guarda em uma tupla, onde cada tupla é uma linha da minha tabela

# 5) Printando o resultado.

print('--- RELATÓRIO DE EQUIPAMENTOS COM TEMPERATURAS CRÍTICAS (MAIORES QUE 80)---')
for tupla in temperaturas_criticas:
  print(f'ID: {tupla[0]}, equipamento: {tupla[1]}, temperatura: {tupla[2]} °C, pressão: {tupla[3]} bar')
else:
  print(f'Não tem equipamentos com temperaturas críticas :D')

conexao.close()

